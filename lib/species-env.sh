#!/usr/bin/env bash
#
# Shared derivation and rendering for a species .env.
#
# init.sh (fresh deployment) and the Tcas migration (preserved deployment)
# provide the values; both render them with the same template so a new key or
# a changed rule only has to be added here.
#
# This file is sourced, not executed.

# trim_url URL — remove trailing slashes, as the URL keys are slash-free.
trim_url() {
  local value=$1
  while [[ "$value" == */ ]]; do
    value="${value%/}"
  done
  printf '%s' "$value"
}

# url_host URL — hostname only: no scheme, userinfo, port or path.
url_host() {
  local rest=${1#*://}
  rest=${rest%%/*}
  if [[ "$rest" == \[* ]]; then
    printf '%s' "${rest%%]*}]"
  else
    printf '%s' "${rest%%:*}"
  fi
}

# internal_keycloak_issuer PORT REALM — server-side issuer on this host. It
# must not use the public URL: the app container does not necessarily trust
# the public certificate or resolve a host-only name.
internal_keycloak_issuer() {
  local port=${1:-8181} realm=$2
  printf 'http://host.docker.internal:%s/keycloak/realms/%s' "$port" "$realm"
}

# render_species_env writes the species .env to stdout.
#
# The caller sets:
#   MAIN_SPECIES EMOBASE_WEB_IMAGE PUBLIC_SERVER PUBLIC_HOST PORTAL_SERVER
#   PORTAL_INTERNAL_URL EMOBASE_INFRA_NETWORK
#   MYSQL_ROOT_PASSWORD DIRECTUS_DB_DATABASE EMOBASE_ES_INDEX_PREFIX
#   KEYCLOAK_PUBLIC_URL KEYCLOAK_INTERNAL_URL INTERNAL_KEYCLOAK_ISSUER
#   KEYCLOAK_REALM KEYCLOAK_REALM_MODE KEYCLOAK_CLIENT_ID
#   KEYCLOAK_CLIENT_SECRET DIRECTUS_SECRET DIRECTUS_ADMIN_EMAIL
#   DIRECTUS_ADMIN_PASSWORD SSR_OIDC_SESSION_SECRET COCO_USERNAME COCO_PASSWORD
#   HTTP_PORT COMPOSE_PROJECT_NAME COMPOSE_FILE PUBLIC_DATA_DIR
#   PRIVATE_DATA_DIR IMAGE_DIR SPECIES_UID SPECIES_GID
#
# Optional:
#   OBA_IMAGE (written only when non-empty)
#   PORTAL_INTERNAL_URL may be empty for a remote portal; Compose then uses
#   PORTAL_SERVER for the internal service URLs.
render_species_env() {
  local missing=() var
  for var in \
    MAIN_SPECIES EMOBASE_WEB_IMAGE PUBLIC_SERVER PUBLIC_HOST PORTAL_SERVER \
    EMOBASE_INFRA_NETWORK MYSQL_ROOT_PASSWORD DIRECTUS_DB_DATABASE \
    EMOBASE_ES_INDEX_PREFIX KEYCLOAK_PUBLIC_URL KEYCLOAK_INTERNAL_URL \
    INTERNAL_KEYCLOAK_ISSUER KEYCLOAK_REALM KEYCLOAK_REALM_MODE \
    KEYCLOAK_CLIENT_ID KEYCLOAK_CLIENT_SECRET DIRECTUS_SECRET \
    DIRECTUS_ADMIN_EMAIL DIRECTUS_ADMIN_PASSWORD SSR_OIDC_SESSION_SECRET \
    COCO_USERNAME COCO_PASSWORD HTTP_PORT COMPOSE_PROJECT_NAME COMPOSE_FILE \
    PUBLIC_DATA_DIR PRIVATE_DATA_DIR IMAGE_DIR SPECIES_UID SPECIES_GID; do
    [[ -n "${!var:-}" ]] || missing+=("$var")
  done
  if (( ${#missing[@]} > 0 )); then
    printf 'ERROR: species env is missing: %s\n' "${missing[*]}" >&2
    return 1
  fi

  cat <<EOF
# Species deployment environment. Generated by emobase-deploy; regenerate it
# with init.sh or the migration instead of editing values by hand.

# 4-letter code of your species (e.g. Tcas, Dmel, Ptep)
MAIN_SPECIES=${MAIN_SPECIES}

# Web UI image
EMOBASE_WEB_IMAGE=${EMOBASE_WEB_IMAGE}

# Local image build instead of pulling from GHCR:
#   docker compose -f compose.yml -f compose.local.yml up -d --build
# Point this at the source checkout; the default assumes it sits next to this
# checkout.
# EMOBASE_WEB_DIR=../emobase-web

# The full address to access the app from public, including protocol and port (if not 80 or 443)
PUBLIC_SERVER=${PUBLIC_SERVER}

# Hostname part of PUBLIC_SERVER. The species nginx answers only this name and
# rejects other Host headers, so use PUBLIC_SERVER when opening the site.
PUBLIC_HOST=${PUBLIC_HOST}

# Public origin of the portal deployment that serves genomics, JBrowse2 and BLAST
PORTAL_SERVER=${PORTAL_SERVER}

# Portal origin used from inside this stack's containers (BLAST proxy, SSR API
# calls). Use an internal hostname/URL when the portal is on the same Docker
# host; otherwise this may be the same as PORTAL_SERVER.
PORTAL_INTERNAL_URL=${PORTAL_INTERNAL_URL}

# ── Shared infrastructure ───────────────────────────────────────────────────
# MySQL, Keycloak and Elasticsearch run in the shared infra stack.
# Start it first. The species stack and its services use these names.
EMOBASE_INFRA_NETWORK=${EMOBASE_INFRA_NETWORK}
DIRECTUS_DB_HOST=mysql
DIRECTUS_DB_PORT=3306
DIRECTUS_DB_USER=root
DIRECTUS_DB_DATABASE=${DIRECTUS_DB_DATABASE}

# This species' Elasticsearch indices in the shared instance. The es-proxy
# sidecar forwards the local name es:9200 to elasticsearch:9200, so the
# application services keep their built-in es:9200 configuration. Indices are
# named <prefix>-<service>-...; never reuse another stack's prefix.
EMOBASE_ES_INDEX_PREFIX=${EMOBASE_ES_INDEX_PREFIX}

# Keycloak endpoint/realm/client. The realm is either an existing realm this
# species joined or a new independent realm owned by this checkout.
KEYCLOAK_PUBLIC_URL=${KEYCLOAK_PUBLIC_URL}
KEYCLOAK_INTERNAL_URL=${KEYCLOAK_INTERNAL_URL}
KEYCLOAK_REALM=${KEYCLOAK_REALM}
KEYCLOAK_REALM_MODE=${KEYCLOAK_REALM_MODE}
KEYCLOAK_CLIENT_ID=${KEYCLOAK_CLIENT_ID}

# Internal service URLs are derived by Compose from the service names and the
# portal origin; only the Keycloak issuer is written here.
# Server-side Keycloak calls go to this server's emobase-infra Keycloak. They
# do not depend on the portal or the public TLS certificate.
INTERNAL_KEYCLOAK_ISSUER=${INTERNAL_KEYCLOAK_ISSUER}
INTERNAL_DIRECTUS_URL=http://directus:8055

# The host port for the local reverse proxy
HTTP_PORT=${HTTP_PORT}

# Project name (prefix for containers)
COMPOSE_PROJECT_NAME=${COMPOSE_PROJECT_NAME}

# Compose files. The species checkout adds its overlay (for example
# compose.tcas.yml) so every docker compose command and the emobase CLI
# include it.
COMPOSE_FILE=${COMPOSE_FILE}

# Directory for data that is publicly downloadable at \$PUBLIC_SERVER/download/
PUBLIC_DATA_DIR=${PUBLIC_DATA_DIR}

# Directory for private data used by internal services
PRIVATE_DATA_DIR=${PRIVATE_DATA_DIR}

# Directory for storing uploaded images
IMAGE_DIR=${IMAGE_DIR}

# uid and gid of the user who can write to the image directory
UID=${SPECIES_UID}
GID=${SPECIES_GID}

# Secrets
# MYSQL_ROOT_PASSWORD is shared with emobase-infra. KEYCLOAK_CLIENT_SECRET
# belongs to this species' chosen realm.
SSR_OIDC_SESSION_SECRET=${SSR_OIDC_SESSION_SECRET}
KEYCLOAK_CLIENT_SECRET=${KEYCLOAK_CLIENT_SECRET}
DIRECTUS_SECRET=${DIRECTUS_SECRET}
MYSQL_ROOT_PASSWORD=${MYSQL_ROOT_PASSWORD}

# Credentials
DIRECTUS_ADMIN_EMAIL=${DIRECTUS_ADMIN_EMAIL}
DIRECTUS_ADMIN_PASSWORD=${DIRECTUS_ADMIN_PASSWORD}

# Seed Keycloak user. For a joined realm these are copied from the owner; for
# a new realm the password is temporary and must be changed on first login.
COCO_USERNAME=${COCO_USERNAME}
COCO_PASSWORD=${COCO_PASSWORD}
EOF

  if [[ -n "${OBA_IMAGE:-}" ]]; then
    printf '\n# Tcas overlay image\nOBA_IMAGE=%s\n' "$OBA_IMAGE"
  fi
}
